"""The project's two Coolify applications, through Coolify's API only (rel coolify=a).

``compose_dockerfile`` turns a template folder's Dockerfile into a self-contained one: each local
``COPY <file> <dest>`` becomes a BuildKit heredoc, so the configuration travels inside the Dockerfile
(no repository). ``stx-version`` and ``requirements.txt`` come from the project's lock folder.

What the API cannot do (4.0.0-beta.468) is printed as manual steps, then checked where possible:
mounting the host folder (Persistent Storage → Directory Mount ``<root>/<face>`` → ``/srv/<face>``), and
replacing the Dockerfile of an existing application (Configuration → Dockerfile, Save, Redeploy).
The Coolify token is read from the target's env file (``coolify_env``), never printed.

A public repository removes the paste: with ``"repo": "owner/name"`` in the target, the faces of
``repo_faces`` (default ``["live"]``) are built by Coolify from ``<dir>/Dockerfile.<face>``, written by
``stx release lock`` and committed. A new streamtex is then ``lock``, commit, push, ``stx release
rebuild``. An application created from a pasted Dockerfile cannot be switched (the API cannot clear it):
``setup --migrate <face>`` creates the application built from the repository and moves the domains to it.
"""

from __future__ import annotations

import base64
import json
import re
import shlex
import time
import urllib.error
import urllib.request
from pathlib import Path

from . import ReleaseError
from .config import ReleaseConfig
from .ops import TEMPLATES

DELIM = "STX_HEREDOC_EOF"
INLINE_SUFFIX = "-inline"       # the name an application built from a pasted Dockerfile keeps after --migrate


def repo_faces(tcfg: dict) -> tuple[str, ...]:
    """The faces Coolify builds from the project's repository (none without ``repo``)."""
    if not tcfg.get("repo"):
        return ()
    faces = tuple(tcfg.get("repo_faces", ["live"]))
    if not faces or any(f not in ("static", "live") for f in faces):
        raise ReleaseError(f"repo_faces {list(faces)} — 'static' and/or 'live'")
    return faces


def dockerfile_path(cfg: ReleaseConfig, face: str) -> Path:
    return cfg.lock_dir / f"Dockerfile.{face}"


def repo_url(repo: str) -> str:
    return repo if "://" in repo else f"https://github.com/{repo.removesuffix('.git')}"


def write_dockerfiles(cfg: ReleaseConfig, faces) -> list[Path]:
    written = []
    for face in faces:
        path = dockerfile_path(cfg, face)
        path.write_text(compose_dockerfile(cfg, face), encoding="utf-8")
        written.append(path)
    return written


def compose_dockerfile(cfg: ReleaseConfig, face: str) -> str:
    folder = TEMPLATES / face
    out = ["# syntax=docker/dockerfile:1",
           f"# GENERATED by stx release (template {face}/) — never edit it: `stx release lock` rewrites it."]
    for line in (folder / "Dockerfile").read_text(encoding="utf-8").splitlines():
        if line.startswith("# STX_RELEASE_APT"):
            if cfg.apt:
                out.append("RUN apt-get update && apt-get install -y --no-install-recommends "
                           + " ".join(cfg.apt) + " && rm -rf /var/lib/apt/lists/*")
            continue
        m = re.match(r"^COPY\s+(?!--from)(.+)$", line.strip())
        if not m:
            out.append(line)
            continue
        parts = shlex.split(m.group(1))
        srcs, dest = parts[:-1], parts[-1]
        for src in srcs:
            for cand in (cfg.lock_dir / src, folder / src, TEMPLATES / "static" / src):
                if cand.is_file():
                    content = cand.read_text(encoding="utf-8")
                    break
            else:
                cand = None
            if cand is None and src == "stx_auth_lib.py":    # the library's login service, unchanged
                from .ops import _stx_auth_source
                content = _stx_auth_source()
            elif cand is None:
                hint = " — run `stx release lock` first" if src in ("stx-version", "requirements.txt") else ""
                raise ReleaseError(f"{face} Dockerfile: {src} not found{hint}")
            if DELIM in content:
                raise ReleaseError(f"{src} holds the delimiter {DELIM}")
            target = dest + src if dest.endswith("/") else dest
            mode = " --chmod=755" if src.endswith(".sh") else ""
            out += [f"COPY{mode} <<'{DELIM}' {target}", content.rstrip("\n"), DELIM]
    return "\n".join(out) + "\n"


class Coolify:
    def __init__(self, root: Path, env_file: str):
        path = Path(env_file).expanduser()
        path = path if path.is_absolute() else root / path
        if not path.is_file():
            raise ReleaseError(f"Coolify credentials: {path} not found (COOLIFY_URL, COOLIFY_API_TOKEN)")
        env = {}
        for line in path.read_text(encoding="utf-8").splitlines():
            if "=" in line and not line.lstrip().startswith("#"):
                k, v = line.split("=", 1)
                env[k.strip()] = v.strip().strip('"').strip("'")
        try:
            self.token, self.url = env["COOLIFY_API_TOKEN"], env["COOLIFY_URL"].rstrip("/")
        except KeyError as e:
            raise ReleaseError(f"{path}: {e.args[0]} is missing") from None

    def call(self, method: str, path: str, body: dict | None = None):
        req = urllib.request.Request(self.url + "/api/v1" + path, method=method,
                                     data=json.dumps(body).encode() if body is not None else None,
                                     headers={"Authorization": f"Bearer {self.token}", "Accept": "application/json",
                                              "Content-Type": "application/json"})
        try:
            with urllib.request.urlopen(req, timeout=60) as r:
                text = r.read().decode()
                return json.loads(text) if text.strip().startswith(("{", "[")) else text
        except urllib.error.HTTPError as e:
            raise ReleaseError(f"Coolify {method} {path} → HTTP {e.code}: {e.read().decode()[:600]}") from None
        except OSError as e:
            raise ReleaseError(f"Coolify {method} {path}: {e}") from None


def domains_for(cfg: ReleaseConfig, tcfg: dict) -> dict[str, str]:
    """Explicit names, never a wildcard (it would pass before the other applications of the server).
    A site with both faces: its name on the live application, ``<name>/html`` on the static one; a site
    with one face: its name on that face's application."""
    d = tcfg.get("domain", "streamtex.org")
    sx = tcfg.get("site_suffix", "")
    static, live = [], []
    for s in cfg.sites:
        if "live" in s.faces:
            live.append(f"https://{s.site}{sx}.{d}")
            if "html" in s.faces:
                static.append(f"https://{s.site}{sx}.{d}/html")
        else:
            static.append(f"https://{s.site}{sx}.{d}")
    return {"static": ",".join(static), "live": ",".join(live)}


def plan(cfg: ReleaseConfig, tcfg: dict) -> list[str]:
    co = Coolify(cfg.root, tcfg["coolify_env"])
    lines = [f"Coolify {co.url} · project {tcfg['coolify_project']}"]
    apps = {x["name"]: x for x in co.call("GET", "/applications")}
    for face in ("static", "live"):
        name = tcfg[f"{face}_app"]
        lines.append(f"  {name}: {'exists' if name in apps else 'TO CREATE'} · Dockerfile "
                     f"{len(compose_dockerfile(cfg, face))} bytes · volume {tcfg['root']}/{face} → /srv/{face}")
    return lines


def _project_and_server(co: Coolify, cfg: ReleaseConfig, tcfg: dict, echo=None) -> tuple[dict, dict]:
    """The Coolify project (created when *echo* is given and it is missing) and server of the target."""
    projects = co.call("GET", "/projects")
    project = next((p for p in projects if p["name"] == tcfg["coolify_project"]), None)
    servers = co.call("GET", "/servers")
    server = next((s for s in servers if s["name"] == tcfg.get("coolify_server", "localhost")), None)
    if server is None:
        raise ReleaseError(f"no Coolify server named '{tcfg.get('coolify_server', 'localhost')}'")
    if not project and echo is None:
        raise ReleaseError(f"no Coolify project named '{tcfg['coolify_project']}' — run `stx release setup --apply`")
    if not project:
        project = co.call("POST", "/projects", {"name": tcfg["coolify_project"],
                                                "description": f"{cfg.project} - stx release"})
        echo(f"  project created: {project.get('uuid')}")
    return project, server


def setup(cfg: ReleaseConfig, tcfg: dict, echo) -> dict:
    """Create the project and the two applications that are missing; returns the uuids to record."""
    co = Coolify(cfg.root, tcfg["coolify_env"])
    project, server = _project_and_server(co, cfg, tcfg, echo)
    apps = {x["name"]: x for x in co.call("GET", "/applications")}
    uuids = {}
    for face in ("static", "live"):
        name = tcfg[f"{face}_app"]
        text = compose_dockerfile(cfg, face)
        app = apps.get(name)
        if not app and face in repo_faces(tcfg):
            uuid = _create_from_repo(co, cfg, tcfg, face, project["uuid"], server["uuid"])
            echo(f"  {name} created, built from {repo_url(tcfg['repo'])}: {uuid}")
        elif not app:
            created = co.call("POST", "/applications/dockerfile", {
                "project_uuid": project["uuid"], "server_uuid": server["uuid"], "environment_name": "production",
                "name": name, "instant_deploy": False, "ports_exposes": "80",
                "dockerfile": base64.b64encode(text.encode("utf-8")).decode("ascii")})
            uuid = created["uuid"]
            echo(f"  {name} created: {uuid}")
        else:
            uuid = app["uuid"]
            co.call("PATCH", f"/applications/{uuid}", {"ports_exposes": "80"})
            if face in repo_faces(tcfg) and _inline(app):
                echo(f"  {name} is built from a pasted Dockerfile: `stx release setup --migrate {face}` "
                     "moves it to the repository")
            elif not _inline(app):
                echo(f"  {name}: built from {app.get('git_repository')} ({app.get('dockerfile_location')})")
            else:
                echo(f"  TO DO in Coolify ({name}): Configuration → Dockerfile, paste the output of "
                     f"`stx release setup --show {face}`, Save, Redeploy (the API cannot change it)")
        _health(co, uuid)
        echo(f"  TO DO in Coolify ({name}): Persistent Storage → Directory Mount "
             f"{tcfg['root']}/{face} → /srv/{face}, then Redeploy")
        uuids[f"{face}_uuid"] = uuid
    return uuids


def _inline(app: dict) -> bool:
    """Built from a Dockerfile pasted in Coolify (it wins over any repository while it is set)."""
    return bool(app.get("dockerfile"))


def _health(co: Coolify, uuid: str) -> None:
    co.call("PATCH", f"/applications/{uuid}", {"custom_docker_run_options": "", "health_check_enabled": True,
                                                "health_check_path": "/_health", "health_check_port": "80"})


def _create_from_repo(co: Coolify, cfg: ReleaseConfig, tcfg: dict, face: str, project_uuid: str,
                      server_uuid: str) -> str:
    rel = dockerfile_path(cfg, face).relative_to(cfg.root).as_posix()
    created = co.call("POST", "/applications/public", {
        "project_uuid": project_uuid, "server_uuid": server_uuid, "environment_name": "production",
        "name": tcfg[f"{face}_app"], "instant_deploy": False, "ports_exposes": "80",
        "git_repository": repo_url(tcfg["repo"]), "git_branch": tcfg.get("repo_branch", "main"),
        "build_pack": "dockerfile", "dockerfile_location": "/" + rel, "base_directory": "/",
        "is_auto_deploy_enabled": False, "autogenerate_domain": False, "health_check_start_period": 180})
    _health(co, created["uuid"])
    return created["uuid"]


def _split_domains(value) -> list[str]:
    return [d.strip() for d in str(value or "").split(",") if d.strip()]


def apply_domains(cfg: ReleaseConfig, tcfg: dict, echo, deploy: bool = False, dry_run: bool = False) -> None:
    """Set both applications' domains from the site list; *dry_run* shows what each would get against
    what it has, and writes nothing (#145, G9)."""
    co = Coolify(cfg.root, tcfg["coolify_env"])
    wanted = domains_for(cfg, tcfg)
    for face in ("static", "live"):
        uuid = tcfg.get(f"{face}_uuid")
        if not uuid:
            raise ReleaseError(f"no {face}_uuid in the target — run `stx release setup --apply` first")
        if dry_run:
            now, want = _split_domains(co.call("GET", f"/applications/{uuid}").get("fqdn")), \
                _split_domains(wanted[face])
            added, removed = [d for d in want if d not in now], [d for d in now if d not in want]
            echo(f"  {tcfg[f'{face}_app']}: {len(want)} domain(s), {len(added)} added, {len(removed)} removed")
            for d in added:
                echo(f"    + {d}")
            for d in removed:
                echo(f"    - {d}")
            continue
        if wanted[face]:
            co.call("PATCH", f"/applications/{uuid}", {"domains": wanted[face]})
        echo(f"  {tcfg[f'{face}_app']}: domains {wanted[face] or '—'}")
        if deploy:
            co.call("GET", f"/deploy?uuid={uuid}")
            echo(f"  {tcfg[f'{face}_app']}: deployment queued")


# -- built from the repository: checks, rebuild, migration -----------------------------------------

def require_pushed_dockerfile(cfg: ReleaseConfig, tcfg: dict, face: str) -> None:
    """Coolify builds the branch as GitHub has it: the Dockerfile there must be the one composed today."""
    from .build import git
    path = dockerfile_path(cfg, face)
    rel = path.relative_to(cfg.root).as_posix()
    wanted = compose_dockerfile(cfg, face)
    if not path.is_file() or path.read_text(encoding="utf-8") != wanted:
        raise ReleaseError(f"{rel} is not the Dockerfile of today's lock — run `stx release lock`, commit, push")
    branch = tcfg.get("repo_branch", "main")
    git(cfg.root, "fetch", "--quiet", "origin", branch)
    try:
        remote = git(cfg.root, "show", f"origin/{branch}:{rel}", strip=False)
    except ReleaseError:
        remote = ""
    if remote != wanted:
        raise ReleaseError(f"{rel} on origin/{branch} is not today's — commit and push it before rebuilding")


def wait_deployment(co: Coolify, deployment: str, echo, timeout: int = 1800) -> None:
    start, last = time.monotonic(), ""
    while time.monotonic() - start < timeout:
        status = co.call("GET", f"/deployments/{deployment}").get("status", "")
        if status != last:
            echo(f"    deployment {status}")
            last = status
        if status == "finished":
            return
        if status in ("failed", "cancelled-by-user"):
            raise ReleaseError(f"Coolify deployment {deployment}: {status} — see its log in Coolify")
        time.sleep(10)
    raise ReleaseError(f"Coolify deployment {deployment}: still '{last}' after {timeout // 60} min")


def _queued(answer: dict) -> str:
    d = answer.get("deployment_uuid") or next((x.get("deployment_uuid") for x in answer.get("deployments", [])), "")
    if not d:
        raise ReleaseError(f"Coolify did not queue a deployment: {answer.get('message', answer)}")
    return d


def deploy(co: Coolify, uuid: str, echo, restart: bool = False) -> None:
    """Build and start (or, with *restart*, start again from the same image) and wait for the end."""
    answer = co.call("POST", f"/applications/{uuid}/restart") if restart else co.call("GET", f"/deploy?uuid={uuid}")
    wait_deployment(co, _queued(answer), echo)


def rebuild(cfg: ReleaseConfig, tcfg: dict, face: str, echo) -> None:
    if face not in repo_faces(tcfg):
        raise ReleaseError(f"the {face} application is built from a pasted Dockerfile — paste "
                           f"`stx release setup --show {face}` in Coolify (Configuration → Dockerfile), Save, Redeploy")
    require_pushed_dockerfile(cfg, tcfg, face)
    co = Coolify(cfg.root, tcfg["coolify_env"])
    uuid = tcfg[f"{face}_uuid"]
    if _inline(co.call("GET", f"/applications/{uuid}")):
        raise ReleaseError(f"{tcfg[f'{face}_app']} is built from a pasted Dockerfile — "
                           f"`stx release setup --migrate {face}` first")
    echo(f"  {tcfg[f'{face}_app']}: building from {repo_url(tcfg['repo'])}")
    deploy(co, uuid, echo)


def migrate(cfg: ReleaseConfig, tcfg: dict, face: str, mounted, echo) -> bool:
    """Move a face from its pasted-Dockerfile application to one built from the repository, in two runs.

    1st run: the old application is renamed ``<name>-inline`` and the new one created (no domain), then the
    volume has to be mounted in Coolify's interface. 2nd run: the new one is built and checked (volume,
    health), takes the domains, and the old one is stopped — kept for a rollback. Returns True when done.
    *mounted(uuid)* tells whether the volume is mounted in the application's container."""
    if face not in repo_faces(tcfg):
        raise ReleaseError(f"no 'repo' (or '{face}' not in repo_faces) in the target")
    require_pushed_dockerfile(cfg, tcfg, face)
    co = Coolify(cfg.root, tcfg["coolify_env"])
    name, old_key = tcfg[f"{face}_app"], f"{face}_uuid{INLINE_SUFFIX.replace('-', '_')}"
    current = co.call("GET", f"/applications/{tcfg[f'{face}_uuid']}")
    if _inline(current):                                   # 1st run
        project, server = _project_and_server(co, cfg, tcfg)
        co.call("PATCH", f"/applications/{current['uuid']}", {"name": name + INLINE_SUFFIX})
        new = _create_from_repo(co, cfg, tcfg, face, project["uuid"], server["uuid"])
        tcfg[old_key], tcfg[f"{face}_uuid"] = current["uuid"], new
        echo(f"  {name + INLINE_SUFFIX}: the application in service, renamed (it keeps serving)")
        echo(f"  {name}: created, built from {repo_url(tcfg['repo'])} ({new}), no domain yet")
        echo(f"  TO DO in Coolify ({name}): Persistent Storage → Directory Mount "
             f"{tcfg['root']}/{face} → /srv/{face} — then run this command again")
        return False
    old = tcfg.get(old_key)
    if not old:
        echo(f"  {name} is already built from {current.get('git_repository')}")
        return True
    echo(f"  {name}: first build from {repo_url(tcfg['repo'])}")
    deploy(co, current["uuid"], echo)
    if not mounted(current["uuid"]):
        raise ReleaseError(f"{name}: /srv/{face} is not mounted — Persistent Storage → Directory Mount "
                           f"{tcfg['root']}/{face} → /srv/{face}, then run this command again")
    wanted = domains_for(cfg, tcfg)[face]
    co.call("PATCH", f"/applications/{old}", {"domains": ""})     # Coolify refuses a domain held twice
    co.call("PATCH", f"/applications/{current['uuid']}", {"domains": wanted})
    echo(f"  {name}: domains {wanted}")
    deploy(co, current["uuid"], echo, restart=True)               # the same image, with its domains
    co.call("POST", f"/applications/{old}/stop")
    echo(f"  {name + INLINE_SUFFIX}: stopped (kept for a rollback; delete it in Coolify when sure)")
    del tcfg[old_key]
    return True
